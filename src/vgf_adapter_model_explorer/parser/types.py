@dataclass
class Header:
    major: int
    minor: int
    patch: int
    encoder_vulkan_headers_version: int
    is_latest_version: bool
    is_valid: bool
    check_version: bool


@dataclass
class Constant:
    index: int
    mrt_index: int
    sparsity_dimension: int
    data: bytes = b""


@dataclass
class IOBase:
    binding: int
    index: int
    mrt_index: int


@dataclass
class Model_Sequence_IO(IOBase):
    name: str


@dataclass
class DescriptorSetInfo:
    index: int
    set_index: int
    bindings: list[IOBase]


@dataclass
class PushConstantRange:
    index: int
    stage_flags: int
    offset: int
    size: int


@dataclass
class Segment:
    constants: list[int]
    descriptor_set_infos: list[DescriptorSetInfo]
    index: int
    dispatch_shape: list[int]
    inputs: list[IOBase]
    outputs: list[IOBase]
    module_index: int
    name: str
    type: ModuleType
    push_constant_ranges: list[PushConstantRange]


@dataclass
class ModelSequence:
    inputs: list[Model_Sequence_IO]
    outputs: list[Model_Sequence_IO]
    segments: list[Segment]


@dataclass
class Module:
    code_size: int
    entry_point: str
    has_spirv: bool
    index: int
    name: str
    type: ModuleType
    code_type: ModuleCodeType = ModuleCodeType.NONE
    code_available: bool = False
    spirv_code: bytes | None = None
    shader_code: str | None = None


@dataclass
class SamplerConfig:
    min_filter: VkFilter
    mag_filter: VkFilter
    address_mode_u: VkSamplerAddressMode
    address_mode_v: VkSamplerAddressMode
    border_color: VkBorderColor


@dataclass
class Resource:
    category: ResourceCategory
    index: int
    shape: list[int]
    stride: list[int]
    vk_descriptor_type: VkDescriptorType | None
    vk_format: VkFormat
    alias_group_id: int | None = None
    sampler_config: SamplerConfig | None = None


@dataclass
class Vgf:
    file_path: str
    header: Header
    resources: list[Resource]
    constants: list[Constant]
    model_sequence: ModelSequence
    modules: list[Module]
