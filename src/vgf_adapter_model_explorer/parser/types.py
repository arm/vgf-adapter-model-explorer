class UnknownIntEnum(IntEnum):
    @classmethod
    def _missing_(cls, value: object) -> Any:
        if not isinstance(value, int):
            return None
        unknown = cast(Any, int.__new__(cls, value))
        unknown._name_ = f"UNKNOWN_{value}"
        unknown._value_ = value
        return unknown


